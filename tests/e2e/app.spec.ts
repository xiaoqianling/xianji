import { expect, test } from '@playwright/test'

test('学习记录和主题在重新打开时保留', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '把日子弹成歌。' })).toBeVisible()
  await page.getByRole('link', { name: '开始第一课' }).click()
  await page.getByRole('button', { name: '标记完成' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: '已完成' })).toBeDisabled()
  await page.getByRole('link', { name: '设置' }).click()
  await page.getByRole('button', { name: /月汐/ }).click()
  await page.getByRole('button', { name: '深色', exact: true }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-palette', 'blue')
  await expect(page.locator('html')).toHaveAttribute('data-mode', 'dark')
})

test('手机布局可搜索并试听一个小节，练习计时可入账', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#songs')
  await page.getByRole('searchbox').fill('欢乐')
  await page.getByRole('button', { name: /欢乐颂/ }).click()
  await page.getByLabel('开始小节').selectOption({ value: '1' })
  await page.getByLabel('结束小节').selectOption({ value: '1' })
  await page.getByRole('button', { name: '循环', exact: true }).click()
  await page.getByRole('button', { name: '试听选段' }).click()
  await expect(page.locator('.tab-active')).toContainText('第 2 小节')
  await page.getByRole('link', { name: '练习', exact: true }).click()
  await page.getByRole('button', { name: '开始节拍' }).click()
  await expect(page.locator('.beat-lights .lit')).toBeVisible()
  await page.getByRole('button', { name: '停止节拍' }).click()
  await page.getByRole('button', { name: '开始循环' }).click()
  await expect(page.locator('.tempo').nth(1)).toContainText('0:59')
  await page.getByRole('button', { name: '结束并记录' }).click()
  await expect(page.getByRole('status')).toContainText('已保存到练习记录')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
